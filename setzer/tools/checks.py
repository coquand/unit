# Checks of OT.seg through its Python mirror (otmirror.py).
#   python3 checks.py linear N     <' is a linear order on T' and on OT, terms of size <= N
#   python3 checks.py rem215 N     Remark 2.15 (b)-(e) on OT terms of size <= N
#   python3 checks.py rem212 N     Remark 2.12 on OT terms of size <= N (functions of otfun.py)
#   python3 checks.py rem214 N     Remark 2.14 on OT terms of size <= N
#   python3 checks.py genf         the cross-check block of OTFTest.seg
#   python3 checks.py aux215 N     the lemmas OTC.seg proves on the way to Remark 2.15
#   python3 checks.py gen          the cross-check block at the end of OTTest.seg
import sys, itertools, random
from otmirror import *

def linear(pool, name):
    for x, y in itertools.combinations(pool, 2):
        if lt(x, y) == lt(y, x):
            print(name, 'not total/asymmetric:', show(x), '|', show(y)); return
    # an asymmetric total relation is transitive iff its scores are distinct
    scores = [sum(lt(y, x) for y in pool) for x in pool]
    if len(set(scores)) < len(pool):
        print(name, 'not transitive'); return
    print(name, 'linear order on', len(pool), 'terms')

ONE = F(Z, Z)
def inCk(k, a, b): return isOT(b) and allLt(G(k, b), a)       # b in C_k(a)
def kminus(k):                                                 # Omega_{s+1}^- = Omega_s, I^- = 0
    if isI(k): return Z
    def drop(t): return t[1] if t[2] == ONE else P(t[1], drop(t[2]))
    s = Z if k[1] == ONE else drop(k[1])
    return s if (isZero(s) or isFi(s)) else O(s)

def rem215(N):
    pool = [x for n in range(1, N + 1) for x in terms(n) if isT(x) and isOT(x)]
    extra = [O(P(ONE, ONE)), O(P(S(I, Z), ONE)), O(P(I, P(ONE, ONE))), O(P(O(ONE), ONE)), O(P(O(P(I, ONE)), ONE))]
    Rs = [k for k in pool if isR(k)] + [k for k in extra if isOT(k)]
    big = pool + Rs + [S(k, b) for k in Rs for b in pool[:40] if isOT(S(k, b))]
    fails = {}
    def bad(tag, *xs):
        fails[tag] = fails.get(tag, 0) + 1
        if fails[tag] <= 3: print(tag, ' | '.join(show(x) for x in xs))
    for k in Rs:
        for a in pool + Rs:
            if not (inCk(k, a, Z) and inCk(k, a, I)): bad('a', k, a)
            for b in big:
                m = inCk(k, a, b)
                if b[0] in ('P', 'F') and m != (inCk(k, a, b[1]) and inCk(k, a, b[2])): bad('b', k, a, b)
                if b[0] == 'O' and m != inCk(k, a, b[1]): bad('b', k, a, b)
                if lt(b, k) and m != lt(b, S(k, a)): bad('c', k, a, b)
                if b[0] == 'S':
                    rhs = inCk(k, a, b[1]) and inCk(k, a, b[2]) and lt(b[2], a)
                    if m != (lt(b, S(k, a)) or rhs): bad('d', k, a, b)
                    if not isI(k) and m != (le(b, kminus(k)) or rhs): bad('e', k, a, b)
    print('Remark 2.15: cardinals', len(Rs), 'b', len(big), 'failures', fails or 'none')

def u(x):
    if x[0] == 'Z': return 'zero'
    if x[0] == 'I': return 'ii'
    if x[0] == 'O': return '(om ' + u(x[1]) + ')'
    return '(' + {'P': 'plus', 'F': 'phi', 'S': 'psi'}[x[0]] + ' ' + u(x[1]) + ' ' + u(x[2]) + ')'

def gen():
    b = lambda v: 'true' if v else 'false'
    random.seed(2026)
    Tp = [x for n in range(1, 8) for x in terms(n) if isT(x)]
    print("-- generated by otmirror.py (the Python mirror of OT.seg): 300 pairs of T' terms of size <= 7")
    for _ in range(300):
        x, y = random.choice(Tp), random.choice(Tp)
        print('#conv lt %s %s = %s ;' % (u(x), u(y), b(lt(x, y))))
    print("-- isOT on 120 random T' terms of size <= 7")
    for x in random.sample(Tp, 120):
        print('#conv isOT %s = %s ;' % (u(x), b(isOT(x))))

import otfun as Fn

def pool(N): return [x for n in range(1, N + 1) for x in terms(n) if isT(x) and isOT(x)]

class Fails:
    def __init__(self): self.d = {}
    def __call__(self, tag, *xs):
        self.d[tag] = self.d.get(tag, 0) + 1
        if self.d[tag] <= 3: print(tag, ' | '.join(show(x) if isinstance(x, tuple) else str(x) for x in xs))
    def report(self, name, n): print(name, 'on', n, 'terms, failures', self.d or 'none')

def rem212(N):
    pl, bad = pool(N), Fails()
    ot = Fn.isOTs
    for x in pl:
        if not ot(Fn.omF(x)): bad('a Om', x)
        if not Fn.le(x, Fn.omF(x)): bad('h Om', x)
        for n in range(4):
            if not ot(Fn.mul(x, n)): bad('a mul', x, n)
            if not ot(Fn.omN(n, x)): bad('a OmN', x, n)
        xs = Fn.summands(x)
        for i in range(1, len(xs)):                       # (c), (d) for x =NF y+z
            y, z = Fn.build(xs[:i]), Fn.build(xs[i:])
            if not (ot(y) and ot(z)): bad('d sum', x, y, z)
            if not (Fn.length(y) < Fn.length(x) and Fn.length(z) < Fn.length(x)): bad('c sum', x)
            if Fn.add(y, z) != x: bad('NF sum', x)
        for y in pl:
            s, p = Fn.add(x, y), Fn.phiF(x, y)
            if not ot(s): bad('a add', x, y)
            if not ot(p): bad('a phi', x, y)
            if not (Fn.le(x, s) and Fn.le(y, s)): bad('h add', x, y, s)
            if not (Fn.le(x, p) and Fn.le(y, p)): bad('h phi', x, y, p)
            if lt(Fn.omF(x), Fn.omF(y)) != lt(x, y): bad('g', x, y)
    small = pool(min(N, 5))
    for x in small:
        for y in small:
            for y2 in small:
                if lt(y, y2) and not lt(Fn.add(x, y), Fn.add(x, y2)): bad('e', x, y, y2)
            for x2 in small:
                for y2 in small:
                    l = lt(Fn.phiF(x, y), Fn.phiF(x2, y2))
                    r = (lt(x, x2) and lt(y, Fn.phiF(x2, y2))) or (x == x2 and lt(y, y2)) or \
                        (lt(x2, x) and lt(Fn.phiF(x, y), y2))
                    if l != r: bad('f', x, y, x2, y2)
    bad.report('Remark 2.12', len(pl))

def subset(M, N): return all(m in N for m in M)

def rem214(N):
    pl, bad = pool(N), Fails()
    ot, le_, lt_ = Fn.isOTs, Fn.le, lt
    Rs = [k for k in pl if isR(k)] + [k for k in [O(P(ONE, ONE)), O(P(S(I, Z), ONE)), O(P(I, ONE)), O(P(O(ONE), ONE))] if ot(k)]
    big = pl + Rs
    for x in big:
        c = Fn.card(x); fs = list(c) + [Fn.mI(x)]
        if not all(ot(v) for v in fs): bad('a', x, *fs)
        t, p, mf, pf = c
        if Fn.plus(t) != p: bad('e', x, t, p)
        y = Z if isZero(t) else (t if isFi(t) else t[1])
        if not (ot(y) and Fn.omF(y) == t and Fn.omF(Fn.suc(y)) == p and le_(t, x) and lt_(x, p)): bad('f', x, y, t, p)
        if lt_(x, S(I, Z)):
            if not (mf == Z and pf == S(I, Z)): bad('g1', x, mf, pf)
        elif lt_(x, I):
            y = mf[2] if mf[0] == 'S' else None
            if not (y is not None and isI(mf[1]) and Fn.inC(I, y, y) and pf == S(I, Fn.suc(y)) and le_(mf, x) and lt_(x, pf)):
                bad('g2', x, mf, pf)
        elif not (mf == I and pf == I): bad('g3', x, mf, pf)
        for n in range(3):
            if not lt_(Fn.omN(n, Fn.suc(x)), Fn.omN(n + 1, Fn.suc(x))): bad('h', x, n)
        if not any(lt_(x, Fn.omN(n, Fn.suc(mf))) for n in range(6)): bad('i', x, mf)
        for k in Rs:                                    # (c)
            if lt_(x, Fn.kminus(k)) and G(k, x): bad('c', x, k)
            if Fn.inC(k, x, x) and ot(S(k, x)) and not ot(S(k, Fn.suc(x))): bad('k2', k, x)
            for a in pl[:60]:
                if Fn.inC(k, a, x) and not Fn.inC(k, a, Fn.suc(x)): bad('k1', k, a, x)
        for k in Rs:                                    # (d), on OT for y
            gk = G(k, x)
            if not (subset(G(k, t), gk) and subset(G(k, mf), gk)): bad('d1', k, x)
            if isR(x) and not subset(G(k, Fn.kminus(x)), gk): bad('d2', k, x)
        for y in big:                                   # (b)
            if le_(x, y):
                cy = Fn.card(y)
                for i, nm in enumerate(['tilde', 'plus', '-Fi', '+Fi']):
                    if not le_(c[i], cy[i]): bad('b ' + nm, x, y)
                if not le_(Fn.mI(x), Fn.mI(y)): bad('b -I', x, y)
    bad.report('Remark 2.14', len(big))

def aux215(N):
    Tp = [x for n in range(1, N + 1) for x in terms(n) if isT(x)]
    pl, bad = [x for x in Tp if isOT(x)], Fails()
    Rs = [k for k in pl if isR(k) and not isI(k)] + [O(P(ONE, ONE)), O(P(S(I, Z), ONE)), O(P(I, ONE)), O(P(O(ONE), ONE))]
    for x in pl:
        if not lt(x, O(x)): bad('lt-om', x)
    for x in Tp:
        if x[0] == 'F' and not (lt(x[1], x) and lt(x[2], x)): bad('phi-below', x)
    for k in Rs:
        km, e = Fn.kminus(k), k[1]
        if not lt(km, k): bad('km < k', k)
        if G(k, k): bad('G-kk', k)
        for d in Tp[:200]:
            if not lt(km, S(k, d)): bad('km < psi', k, d)
        for x in pl:
            if le(hd(x), km) and G(k, x): bad('z-main', k, x)
            if x[0] == 'S' and lt(x, k) and x[1] != k and not le(x, km): bad('w-I/w-S', k, x)
        if e != ONE:
            for x in Tp:
                if lt(x, e) and not le(x, Fn.pred1(e)): bad('lt-succ', e, x)
    bad.report('Lemmas for Remark 2.15', len(Tp))

def addR(a, b):                                   # + as the recursion of OTF.seg
    if isZero(a): return b
    if isZero(b): return a
    h = b[1] if b[0] == 'P' else b
    if a[0] == 'P': return P(a[1], addR(a[2], b)) if le(h, a[1]) else b
    return P(a, b) if le(h, a) else b

def nat(k): return 'nz' if k == 0 else '(ns ' + nat(k - 1) + ')'

def genf():
    random.seed(2027)
    pl = pool(7)
    bad = [(x, y) for x in pl for y in pl if addR(x, y) != Fn.add(x, y)]
    print("-- generated by tools/checks.py genf (the mirror tools/otfun.py), on OT terms of size <= 7;")
    print("-- the recursion for + agrees with Setzer's definition on all %d pairs (%d failures)" % (len(pl) ** 2, len(bad)))
    for _ in range(80):
        x, y = random.choice(pl), random.choice(pl)
        print('#conv add %s %s = %s ;' % (u(x), u(y), u(Fn.add(x, y))))
        print('#conv phiF %s %s = %s ;' % (u(x), u(y), u(Fn.phiF(x, y))))
    for x in random.sample(pl, 60):
        k = random.randrange(4)
        print('#conv mul %s %s = %s ;' % (u(x), nat(k), u(Fn.mul(x, k))))
        print('#conv omN %s %s = %s ;' % (nat(k), u(x), u(Fn.omN(k, x))))
        for f, g in [('tilde', Fn.tilde), ('up', Fn.plus), ('mFi', Fn.mFi), ('pFi', Fn.pFi), ('mI', Fn.mI)]:
            print('#conv %s %s = %s ;' % (f, u(x), u(g(x))))

