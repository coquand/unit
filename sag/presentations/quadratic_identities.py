"""Generate ordinary Seg equality proofs from semiring rewrites.

This script is not trusted: every generated equality is checked by segd.
It changes only QuadraticIdentities.seg next to this script.
"""
from pathlib import Path

def add(x, y): return ('add', x, y)
def mul(x, y): return ('mul', x, y)
def show(x):
    return x if isinstance(x, str) else f'({x[0]} {show(x[1])} {show(x[2])})'
def get(x, path):
    for i in path: x = x[i]
    return x
def put(x, path, y):
    if not path: return y
    z = list(x); z[path[0]] = put(z[path[0]], path[1:], y)
    return tuple(z)
def nodes(x, path=()):
    if isinstance(x, tuple):
        yield from nodes(x[1], path+(1,))
        yield from nodes(x[2], path+(2,))
        yield path, x
def law(name, *xs): return '('+name+' '+' '.join(show(x) for x in xs)+')'
def key(x):
    if isinstance(x, str): return (x,)
    assert x[0]=='mul', x
    return key(x[1])+key(x[2])
def normalize(start):
    x=start; steps=[]
    def step(path,y,p):
        nonlocal x
        old=get(x,path)
        if path:
            p=f'(Pr.ap R R (\\ v -> {show(put(x,path,"v"))}) {show(old)} {show(y)} {p})'
        x=put(x,path,y); steps.append((p,x))
    # Distributivity and right association, until fully expanded.
    while True:
        for path,e in nodes(x):
            op,a,b=e
            if op=='mul' and isinstance(b,tuple) and b[0]=='add':
                step(path,add(mul(a,b[1]),mul(a,b[2])),law('dist',a,b[1],b[2])); break
            if op=='mul' and isinstance(a,tuple) and a[0]=='add':
                step(path,add(mul(a[1],b),mul(a[2],b)),law('dist-left',a[1],a[2],b)); break
            if isinstance(a,tuple) and a[0]==op:
                step(path,(op,a[1],(op,a[2],b)),f'(sym {law(op+"A",a[1],a[2],b)})'); break
        else: break
    # Sort the factors of each monomial.
    while True:
        for path,e in nodes(x):
            op,a,b=e
            if op!='mul': continue
            if isinstance(b,tuple):
                if key(a)>key(b[1]):
                    step(path,mul(b[1],mul(a,b[2])),law('mul-swap',a,b[1],b[2])); break
            elif key(a)>key(b):
                step(path,mul(b,a),law('mulC',a,b)); break
        else: break
    # Sort the monomials, without combining equal summands.
    while True:
        for path,e in nodes(x):
            op,a,b=e
            if op!='add': continue
            if isinstance(b,tuple) and b[0]=='add':
                if key(a)>key(b[1]):
                    step(path,add(b[1],add(a,b[2])),law('add-swap',a,b[1],b[2])); break
            elif key(a)>key(b):
                step(path,add(b,a),law('addC',a,b)); break
        else: break
    return x,steps

header='''-- Generated by quadratic_identities.py; all proofs use only CRing laws.
level l ; open Ring[l] ;
module Pr = Prelude[l] ;
module Laws (Rg : CRing) {
 open Rg ; open RL[Rg] ;
 dist-left (x y w : R) : Id R (mul (add x y) w) (add (mul x w) (mul y w)) =
  trans (mulC (add x y) w) (trans (dist w x y)
   (Presentations[l].cong2 R add _ _ _ _ (mulC w x) (mulC w y))) ;
 add-swap (x y w : R) : Id R (add x (add y w)) (add y (add x w)) =
  trans (addA x y w) (trans (ap (\\ t -> add t w) (addC x y)) (sym (addA y x w))) ;
'''
def emit(name,args,lhs,rhs):
    nl,sl=normalize(lhs); nr,sr=normalize(rhs)
    assert nl==nr,(name,nl,nr)
    steps=sl+[(f'(sym {p})',before) for before,(p,after) in reversed(list(zip([rhs]+[e for _,e in sr[:-1]],sr)))]
    out=f' {name} ({" ".join(args)} : R) : Id R {show(lhs)} {show(rhs)} = calc R {{\n  {show(lhs)}\n'
    out+=''.join(f'   =< {p} > {show(e)}\n' for p,e in steps)
    return out+' } ;\n'
a,b,c,d,e,f,g,t='a b c d e f g t'.split()
def product(p,q):
    return (add(mul(p[0],q[0]),mul(a,mul(p[1],q[1]))),add(mul(p[0],q[1]),mul(p[1],q[0])))
def summation(p,q): return (add(p[0],q[0]),add(p[1],q[1]))
parts=[header]
p,q,r=(b,c),(d,e),(f,g)
for i in range(2):
    parts.append(emit('associative'+str(i),[a,b,c,d,e,f,g],product(p,product(q,r))[i],product(product(p,q),r)[i]))
    parts.append(emit('distributive'+str(i),[a,b,c,d,e,f,g],product(p,summation(q,r))[i],summation(product(p,q),product(p,r))[i]))
parts.append(emit('affine-add',[b,c,d,e,t],add(add(b,d),mul(add(c,e),t)),add(add(b,mul(c,t)),add(d,mul(e,t)))))
parts.append(emit('affine-mul',[b,c,d,e,t],mul(add(b,mul(c,t)),add(d,mul(e,t))),
                 add(add(mul(b,d),mul(mul(c,e),mul(t,t))),mul(add(mul(b,e),mul(c,d)),t))))
parts.append('} ;\n')
Path(__file__).with_name('QuadraticIdentities.seg').write_text(''.join(parts))
